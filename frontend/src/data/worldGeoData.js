/**
 * Fast local search matching countries and cities without network calls
 */
export const searchGeographicLocations = (query, limit = 8) => {
  if (!query || typeof query !== 'string' || query.trim().length === 0) {
    return [];
  }

  const q = query.toLowerCase().trim();
  const exactMatches = [];
  const prefixMatches = [];
  const substringMatches = [];

  // Match cities
  for (const city of WORLD_CITIES) {
    const nameLower = city.name.toLowerCase();
    const item = {
      type: 'city',
      id: city.id,
      name: city.name,
      subtitle: `${city.country} • ${city.region || ''} ${city.isCapital ? '⭐ Capital' : ''}`,
      country: city.country,
      countryCode: city.countryCode,
      region: city.region,
      lat: city.lat,
      lon: city.lon,
      tier: city.tier,
      population: city.population,
      isCapital: city.isCapital,
    };

    if (nameLower === q) {
      exactMatches.push(item);
    } else if (nameLower.startsWith(q)) {
      prefixMatches.push(item);
    } else if (
      nameLower.includes(q) ||
      city.country.toLowerCase().includes(q) ||
      city.region?.toLowerCase().includes(q)
    ) {
      substringMatches.push(item);
    }
  }

  // Match countries
  for (const country of WORLD_COUNTRIES) {
    const nameLower = country.name.toLowerCase();
    const item = {
      type: 'country',
      id: country.id,
      name: country.name,
      subtitle: `Country • Capital: ${country.capital} • ${country.region}`,
      capital: country.capital,
      lat: country.lat,
      lon: country.lon,
      countryCode: country.code,
      region: country.region,
      population: country.population,
    };

    if (nameLower === q || country.code.toLowerCase() === q) {
      exactMatches.push(item);
    } else if (nameLower.startsWith(q)) {
      prefixMatches.push(item);
    } else if (
      nameLower.includes(q) ||
      country.capital.toLowerCase().includes(q)
    ) {
      substringMatches.push(item);
    }
  }

  return [...exactMatches, ...prefixMatches, ...substringMatches].slice(0, limit);
};

/**
 * Haversine distance in kilometers between two geographic coordinates
 */
export const haversineDistanceKm = (lat1, lon1, lat2, lon2) => {
  const R = 6371; // Earth's mean radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
};

/**
 * Aggregates live DisasterChain emergency records within a spatial radius around a city/country
 */
export const computeSpatialEmergencyTelemetry = ({
  lat,
  lon,
  radiusKm = 150,
  sosList = [],
  incidents = [],
  shelters = [],
  alerts = [],
  riskZones = [],
}) => {
  const nearbySos = sosList.filter((s) => {
    if (s.latitude == null || s.longitude == null) return false;
    return haversineDistanceKm(lat, lon, s.latitude, s.longitude) <= radiusKm;
  });

  const nearbyIncidents = incidents.filter((i) => {
    if (i.latitude == null || i.longitude == null) return false;
    return haversineDistanceKm(lat, lon, i.latitude, i.longitude) <= radiusKm;
  });

  const nearbyShelters = shelters.filter((sh) => {
    if (sh.latitude == null || sh.longitude == null) return false;
    return haversineDistanceKm(lat, lon, sh.latitude, sh.longitude) <= radiusKm;
  });

  const nearbyAlerts = alerts.filter((a) => {
    // If alert has lat/lon
    if (a.latitude != null && a.longitude != null) {
      return haversineDistanceKm(lat, lon, a.latitude, a.longitude) <= radiusKm;
    }
    return true; // Broader national/regional alerts
  });

  const nearbyRiskZones = riskZones.filter((z) => {
    if (z.latitude == null || z.longitude == null) return false;
    return haversineDistanceKm(lat, lon, z.latitude, z.longitude) <= radiusKm;
  });

  // Calculate local risk level based on live signals
  let calculatedRisk = 'LOW';
  const totalSignals = nearbySos.length * 3 + nearbyIncidents.length * 2 + nearbyAlerts.length;
  if (nearbySos.some((s) => s.severity === 'Critical') || totalSignals >= 10 || nearbyRiskZones.some((z) => z.riskLevel === 'CRITICAL')) {
    calculatedRisk = 'CRITICAL';
  } else if (totalSignals >= 5 || nearbyRiskZones.some((z) => z.riskLevel === 'HIGH')) {
    calculatedRisk = 'HIGH';
  } else if (totalSignals >= 2 || nearbyRiskZones.some((z) => z.riskLevel === 'MEDIUM')) {
    calculatedRisk = 'MEDIUM';
  }

  const availableShelterBeds = nearbyShelters.reduce(
    (acc, sh) => acc + Math.max(0, (sh.capacity || 0) - (sh.occupancy || 0)),
    0
  );

  return {
    sosCount: nearbySos.length,
    incidentCount: nearbyIncidents.length,
    shelterCount: nearbyShelters.length,
    availableShelterBeds,
    alertCount: nearbyAlerts.length,
    riskLevel: calculatedRisk,
    hasActiveCrisis: nearbySos.length > 0 || nearbyIncidents.length > 0,
    nearbySos,
    nearbyIncidents,
    nearbyShelters,
  };
};
